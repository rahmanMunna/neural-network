// Copies every "#region" in examples/ into lib/backend/snippets.generated.ts.
// The code shown on the site is therefore the same code the example tests run.
// Regions are addressed as "<topic>/<file>#<region>".

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const examples = join(root, "examples");
const out = join(root, "lib/backend/snippets.generated.ts");

const LANG = { ".ts": "ts", ".sql": "sql", ".conf": "nginx", ".yml": "yaml" };
const START = /^\s*(?:\/\/|#|--)\s*#region\s+(\S+)\s*$/;
const END = /^\s*(?:\/\/|#|--)\s*#endregion\s*$/;

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules") continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

/** Removes the indent shared by every non-empty line. */
function dedent(lines) {
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length));
  return lines.map((l) => l.slice(indent)).join("\n").trimEnd();
}

const snippets = {};

for (const path of walk(examples)) {
  const ext = extname(path);
  if (!LANG[ext] || path.endsWith(".test.ts")) continue;
  const name = relative(examples, path).replaceAll("\\", "/");
  const lines = readFileSync(path, "utf8").split(/\r?\n/);

  if (ext === ".yml") {
    snippets[name] = { lang: LANG[ext], file: name, code: lines.join("\n").trimEnd() };
  }

  let id = null;
  let body = [];
  for (const line of lines) {
    const start = line.match(START);
    if (start) {
      if (id) throw new Error(`${name}: nested region ${start[1]}`);
      id = start[1];
      body = [];
    } else if (END.test(line)) {
      if (!id) throw new Error(`${name}: #endregion with no region`);
      snippets[`${name}#${id}`] = { lang: LANG[ext], file: name, code: dedent(body) };
      id = null;
    } else if (id) {
      body.push(line);
    }
  }
  if (id) throw new Error(`${name}: region ${id} never closed`);
}

const sorted = Object.fromEntries(Object.entries(snippets).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  out,
  `// Generated by scripts/gen-snippets.mjs from examples/. Do not edit by hand.\n\n` +
    `export const SNIPPETS = ${JSON.stringify(sorted, null, 2)} as const;\n\n` +
    `export type SnippetId = keyof typeof SNIPPETS;\n`,
);
console.log(`snippets: ${Object.keys(sorted).length}`);
